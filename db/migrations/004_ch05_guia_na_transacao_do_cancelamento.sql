SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

ALTER SESSION SET DDL_LOCK_TIMEOUT = 30;

CREATE OR REPLACE TRIGGER TRG_NFSE_SITUACAO_GUIA
FOR UPDATE OF SITUACAO ON NFSE
COMPOUND TRIGGER

    TYPE t_guia IS RECORD (PRESTADOR_ID NFSE.PRESTADOR_ID%TYPE, COMPETENCIA NFSE.COMPETENCIA%TYPE);
    TYPE t_guias IS TABLE OF t_guia INDEX BY VARCHAR2(60);
    v_guias t_guias;
    v_chave VARCHAR2(60);

    AFTER EACH ROW IS
    BEGIN
        v_chave := :NEW.PRESTADOR_ID || '|' || TO_CHAR(:NEW.COMPETENCIA, 'YYYYMMDD');
        v_guias(v_chave).PRESTADOR_ID := :NEW.PRESTADOR_ID;
        v_guias(v_chave).COMPETENCIA := :NEW.COMPETENCIA;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        v_chave := v_guias.FIRST;
        WHILE v_chave IS NOT NULL LOOP
            PKG_GUIA.recalcular_guia(v_guias(v_chave).PRESTADOR_ID, v_guias(v_chave).COMPETENCIA);
            v_chave := v_guias.NEXT(v_chave);
        END LOOP;
    END AFTER STATEMENT;

END TRG_NFSE_SITUACAO_GUIA;
/

SHOW ERRORS

DECLARE
    v_status USER_OBJECTS.STATUS%TYPE;
BEGIN
    SELECT STATUS
      INTO v_status
      FROM USER_OBJECTS
     WHERE OBJECT_NAME = 'TRG_NFSE_SITUACAO_GUIA'
       AND OBJECT_TYPE = 'TRIGGER';

    IF v_status <> 'VALID' THEN
        RAISE_APPLICATION_ERROR(-20001, 'TRG_NFSE_SITUACAO_GUIA invalido');
    END IF;
END;
/

EXIT
