SET VERIFY OFF FEEDBACK OFF LINESIZE 200 PAGESIZE 100
WHENEVER SQLERROR EXIT FAILURE

DEFINE INSCRICAO = '&1'
DEFINE MES = '&2'

PROMPT
PROMPT 1. Guia x soma do ISS das notas
SELECT TO_CHAR(g.COMPETENCIA, 'MM/YYYY') AS COMPETENCIA,
       g.SITUACAO,
       g.VALOR_ISS AS GUIA,
       (SELECT NVL(SUM(n.VALOR_ISS), 0)
          FROM NFSE n
         WHERE n.PRESTADOR_ID = g.PRESTADOR_ID
           AND n.COMPETENCIA = g.COMPETENCIA
           AND n.SITUACAO = 'N'
           AND n.ISS_RETIDO = 'N') AS SOMA_NOTAS
  FROM GUIAS g
  JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
   AND g.COMPETENCIA = TO_DATE('&MES', 'YYYY-MM');

PROMPT
PROMPT 2. Notas com ISS divergente da regra
SELECT n.NUMERO,
       TO_CHAR(n.DT_EMISSAO, 'DD/MM/YYYY HH24:MI') AS EMISSAO,
       n.BASE_CALCULO,
       n.ALIQUOTA,
       n.VALOR_ISS AS ISS_NOTA,
       ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2) AS ISS_CALCULADO,
       ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2) - n.VALOR_ISS AS DIFERENCA
  FROM NFSE n
  JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
   AND n.COMPETENCIA = TO_DATE('&MES', 'YYYY-MM')
   AND n.SITUACAO = 'N'
   AND n.ISS_RETIDO = 'N'
   AND n.VALOR_ISS <> ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2)
 ORDER BY n.NUMERO;

PROMPT
PROMPT 3. Resumo das divergencias
SELECT COUNT(*) AS TOTAL_NOTAS,
       NVL(SUM(ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2) - n.VALOR_ISS), 0) AS DIFERENCA_TOTAL
  FROM NFSE n
  JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
   AND n.COMPETENCIA = TO_DATE('&MES', 'YYYY-MM')
   AND n.SITUACAO = 'N'
   AND n.ISS_RETIDO = 'N'
   AND n.VALOR_ISS <> ROUND(n.BASE_CALCULO * n.ALIQUOTA, 2);

UNDEFINE INSCRICAO
UNDEFINE MES
EXIT
