SET VERIFY OFF FEEDBACK OFF LINESIZE 200 PAGESIZE 100
WHENEVER SQLERROR EXIT FAILURE

DEFINE INSCRICAO = '&1'

COLUMN SERIE FORMAT A6
COLUMN NOTAS_EMITIDAS FORMAT A30
COLUMN PROTOCOLOS FORMAT A60

PROMPT
PROMPT 1. Lotes do prestador: RPS enviados x resposta no retorno
WITH lotes AS (
    SELECT l.PROTOCOLO, l.QTD_RPS, l.SITUACAO, l.XML_LOTE, l.ERROS, l.DT_RECEBIMENTO
      FROM LOTES_RPS l
      JOIN CONTRIBUINTES c ON c.ID = l.PRESTADOR_ID
     WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
),
rps_enviados AS (
    SELECT l.PROTOCOLO, x.NUMERO
      FROM lotes l,
           XMLTABLE('//*[local-name()="InfRps"]' PASSING XMLTYPE(l.XML_LOTE)
                    COLUMNS NUMERO NUMBER PATH '*[local-name()="IdentificacaoRps"]/*[local-name()="Numero"]') x
),
erros AS (
    SELECT l.PROTOCOLO, e.NUMERO, e.MENSAGEM
      FROM lotes l,
           XMLTABLE('//*[local-name()="MensagemRetorno"]' PASSING XMLTYPE(l.ERROS)
                    COLUMNS NUMERO   NUMBER         PATH '*[local-name()="IdentificacaoRps"]/*[local-name()="Numero"]',
                            MENSAGEM VARCHAR2(4000) PATH '*[local-name()="Mensagem"]') e
     WHERE l.ERROS IS NOT NULL
),
notas AS (
    SELECT r.PROTOCOLO, r.NUMERO
      FROM RPS r
      JOIN NFSE n ON n.RPS_ID = r.ID
     WHERE r.PROTOCOLO IN (SELECT PROTOCOLO FROM lotes)
)
SELECT l.PROTOCOLO,
       l.QTD_RPS,
       l.SITUACAO,
       (SELECT COUNT(*) FROM notas n WHERE n.PROTOCOLO = l.PROTOCOLO) AS NOTAS,
       (SELECT COUNT(*) FROM erros e WHERE e.PROTOCOLO = l.PROTOCOLO) AS ERROS,
       (SELECT COUNT(*) FROM erros e
         WHERE e.PROTOCOLO = l.PROTOCOLO
           AND INSTR(e.MENSAGEM, 'ORA-00001') > 0) AS ORA_00001,
       (SELECT COUNT(*) FROM erros e
         WHERE e.PROTOCOLO = l.PROTOCOLO
           AND EXISTS (SELECT 1 FROM rps_enviados x WHERE x.PROTOCOLO = e.PROTOCOLO)
           AND NOT EXISTS (SELECT 1 FROM rps_enviados x WHERE x.PROTOCOLO = e.PROTOCOLO AND x.NUMERO = e.NUMERO)) AS ERROS_OUTRO_LOTE,
       (SELECT COUNT(*) FROM rps_enviados x
         WHERE x.PROTOCOLO = l.PROTOCOLO
           AND NOT EXISTS (SELECT 1 FROM notas n WHERE n.PROTOCOLO = x.PROTOCOLO AND n.NUMERO = x.NUMERO)
           AND NOT EXISTS (SELECT 1 FROM erros e WHERE e.PROTOCOLO = x.PROTOCOLO AND e.NUMERO = x.NUMERO)) AS SEM_RESPOSTA
  FROM lotes l
 ORDER BY l.DT_RECEBIMENTO, l.PROTOCOLO;

PROMPT
PROMPT 2. RPS do prestador com mais de uma nota
SELECT NVL(r.SERIE, '(nula)') AS SERIE,
       r.NUMERO,
       COUNT(*) AS NOTAS,
       LISTAGG(n.NUMERO, ', ') WITHIN GROUP (ORDER BY n.NUMERO) AS NOTAS_EMITIDAS,
       LISTAGG(r.PROTOCOLO, ', ') WITHIN GROUP (ORDER BY n.NUMERO) AS PROTOCOLOS
  FROM RPS r
  JOIN NFSE n ON n.RPS_ID = r.ID
  JOIN CONTRIBUINTES c ON c.ID = r.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
 GROUP BY r.SERIE, r.NUMERO
HAVING COUNT(*) > 1
 ORDER BY r.SERIE, r.NUMERO;

PROMPT
PROMPT 3. Numeracao do prestador
SELECT COUNT(*) AS NOTAS,
       COUNT(DISTINCT n.NUMERO) AS NUMEROS_DISTINTOS,
       MIN(n.NUMERO) AS MENOR,
       MAX(n.NUMERO) AS MAIOR,
       NVL(MAX(n.NUMERO) - MIN(n.NUMERO) + 1 - COUNT(*), 0) AS LACUNAS
  FROM NFSE n
  JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO';

PROMPT
PROMPT 4. Impacto na base: prestadores com RPS que gerou mais de uma nota
SELECT c.INSCRICAO_MUNICIPAL,
       COUNT(*) AS RPS_DUPLICADOS,
       SUM(d.NOTAS - 1) AS NOTAS_A_MAIS,
       TO_CHAR(MIN(d.PRIMEIRA), 'DD/MM/YYYY HH24:MI') AS PRIMEIRA
  FROM (SELECT r.PRESTADOR_ID, r.SERIE, r.NUMERO, COUNT(*) AS NOTAS, MIN(n.DT_EMISSAO) AS PRIMEIRA
          FROM RPS r
          JOIN NFSE n ON n.RPS_ID = r.ID
         GROUP BY r.PRESTADOR_ID, r.SERIE, r.NUMERO
        HAVING COUNT(*) > 1) d
  JOIN CONTRIBUINTES c ON c.ID = d.PRESTADOR_ID
 GROUP BY c.INSCRICAO_MUNICIPAL
 ORDER BY 1;

PROMPT
PROMPT 5. Impacto na base: lotes com ORA-00001 no retorno
SELECT c.INSCRICAO_MUNICIPAL,
       COUNT(*) AS LOTES,
       TO_CHAR(MIN(l.DT_RECEBIMENTO), 'DD/MM/YYYY HH24:MI') AS PRIMEIRO
  FROM LOTES_RPS l
  JOIN CONTRIBUINTES c ON c.ID = l.PRESTADOR_ID
 WHERE DBMS_LOB.INSTR(l.ERROS, 'ORA-00001') > 0
 GROUP BY c.INSCRICAO_MUNICIPAL
 ORDER BY 1;

UNDEFINE INSCRICAO
EXIT
