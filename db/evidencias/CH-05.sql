WHENEVER SQLERROR EXIT FAILURE

DEFINE INSCRICAO = '&1'
DEFINE MES = '&2'

COLUMN MOTIVO FORMAT A40

PROMPT
PROMPT 1. Guia x valor recalculado pelas notas normais e nao retidas
SELECT TO_CHAR(g.COMPETENCIA, 'MM/YYYY') AS COMPETENCIA,
       g.SITUACAO,
       g.VALOR_ISS AS GUIA,
       (SELECT NVL(SUM(ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2)), 0)
          FROM NFSE n
         WHERE n.PRESTADOR_ID = g.PRESTADOR_ID
           AND n.COMPETENCIA = g.COMPETENCIA
           AND n.SITUACAO = 'N'
           AND n.ISS_RETIDO = 'N') AS VALOR_CORRETO,
       TO_CHAR(g.DT_ATUALIZACAO, 'DD/MM/YYYY HH24:MI:SS') AS ATUALIZADA_EM
  FROM GUIAS g
  JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
   AND g.COMPETENCIA = TO_DATE('&MES', 'YYYY-MM');

PROMPT
PROMPT 2. Notas canceladas da competencia
SELECT n.NUMERO,
       ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2) AS ISS,
       n.ISS_RETIDO,
       TO_CHAR(n.DT_CANCELAMENTO, 'DD/MM/YYYY HH24:MI:SS') AS CANCELADA_EM,
       n.MOTIVO_CANCELAMENTO AS MOTIVO
  FROM NFSE n
  JOIN CONTRIBUINTES c ON c.ID = n.PRESTADOR_ID
 WHERE c.INSCRICAO_MUNICIPAL = '&INSCRICAO'
   AND n.COMPETENCIA = TO_DATE('&MES', 'YYYY-MM')
   AND n.SITUACAO = 'C'
 ORDER BY n.NUMERO;

PROMPT
PROMPT 3. Base inteira: guias que divergem do valor recalculado, por situacao
SELECT g.SITUACAO,
       COUNT(*) AS GUIAS,
       COUNT(DISTINCT g.PRESTADOR_ID) AS CONTRIBUINTES,
       SUM(g.VALOR_ISS - NVL(s.VALOR, 0)) AS COBRADO_A_MAIS
  FROM GUIAS g
  LEFT JOIN (SELECT n.PRESTADOR_ID, n.COMPETENCIA,
                    SUM(ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2)) AS VALOR
               FROM NFSE n
              WHERE n.SITUACAO = 'N'
                AND n.ISS_RETIDO = 'N'
              GROUP BY n.PRESTADOR_ID, n.COMPETENCIA) s
    ON s.PRESTADOR_ID = g.PRESTADOR_ID AND s.COMPETENCIA = g.COMPETENCIA
 WHERE g.VALOR_ISS <> NVL(s.VALOR, 0)
 GROUP BY g.SITUACAO
 ORDER BY g.SITUACAO;

PROMPT
PROMPT 4. Base inteira: as 20 maiores divergencias
SELECT *
  FROM (SELECT c.INSCRICAO_MUNICIPAL,
               TO_CHAR(g.COMPETENCIA, 'MM/YYYY') AS COMPETENCIA,
               g.SITUACAO,
               g.VALOR_ISS AS GUIA,
               NVL(s.VALOR, 0) AS VALOR_CORRETO,
               g.VALOR_ISS - NVL(s.VALOR, 0) AS COBRADO_A_MAIS
          FROM GUIAS g
          JOIN CONTRIBUINTES c ON c.ID = g.PRESTADOR_ID
          LEFT JOIN (SELECT n.PRESTADOR_ID, n.COMPETENCIA,
                            SUM(ROUND((n.VALOR_SERVICOS - n.VALOR_DEDUCOES) * n.ALIQUOTA, 2)) AS VALOR
                       FROM NFSE n
                      WHERE n.SITUACAO = 'N'
                        AND n.ISS_RETIDO = 'N'
                      GROUP BY n.PRESTADOR_ID, n.COMPETENCIA) s
            ON s.PRESTADOR_ID = g.PRESTADOR_ID AND s.COMPETENCIA = g.COMPETENCIA
         WHERE g.VALOR_ISS <> NVL(s.VALOR, 0)
         ORDER BY ABS(g.VALOR_ISS - NVL(s.VALOR, 0)) DESC)
 WHERE ROWNUM <= 20;

UNDEFINE INSCRICAO
