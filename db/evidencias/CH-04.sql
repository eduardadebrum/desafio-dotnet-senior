PROMPT 6. Cursores da aplicacao na V$SQL (consulta de servicos tomados)
COLUMN SQL_ID FORMAT A14
COLUMN PRIMEIRA_CARGA FORMAT A20
COLUMN ACESSO_NFSE FORMAT A30
SELECT s.SQL_ID,
       s.CHILD_NUMBER AS FILHO,
       s.EXECUTIONS AS EXECUCOES,
       ROUND(s.BUFFER_GETS / NULLIF(s.EXECUTIONS, 0)) AS BLOCOS_POR_EXEC,
       ROUND(s.ELAPSED_TIME / NULLIF(s.EXECUTIONS, 0) / 1000, 1) AS MS_POR_EXEC,
       s.FIRST_LOAD_TIME AS PRIMEIRA_CARGA,
       (SELECT MAX(p.OPTIONS || ' ' || p.OBJECT_NAME)
          FROM V$SQL_PLAN p
         WHERE p.SQL_ID = s.SQL_ID AND p.CHILD_NUMBER = s.CHILD_NUMBER
           AND p.OBJECT_NAME IN ('NFSE', 'IX_NFSE_TOMADOR_DT')
           AND p.OPTIONS IN ('FULL', 'RANGE SCAN')) AS ACESSO_NFSE
  FROM V$SQL s
 WHERE s.SQL_FULLTEXT LIKE '%FROM NFSE n JOIN CONTRIBUINTES p%n.TOMADOR_DOCUMENTO = :doc%:deslocamento%'
   AND s.SQL_FULLTEXT NOT LIKE '%:prest%'
   AND s.SQL_FULLTEXT NOT LIKE '%V$SQL%'
 ORDER BY s.FIRST_LOAD_TIME;

